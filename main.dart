class DhikrListScreen extends StatefulWidget {
  final DhikrCategory category;
  const DhikrListScreen({Key? key, required this.category}) : super(key: key);

  @override
  State<DhikrListScreen> createState() => _DhikrListScreenState();
}

class _DhikrListScreenState extends State<DhikrListScreen> {
  late List<int?> remainingCounts;

  @override
  void initState() {
    super.initState();
    remainingCounts = widget.category.items.map((item) => item.count).toList();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.category.title, style: const TextStyle(color: gold)),
        backgroundColor: cardBg,
        iconTheme: const IconThemeData(color: gold),
        centerTitle: true,
      ),
      body: ListView.builder(
        padding: const EdgeInsets.all(12),
        itemCount: widget.category.items.length,
        itemBuilder: (context, index) {
          final item = widget.category.items[index];
          final currentCount = remainingCounts[index];
          final isCompleted = currentCount != null && currentCount <= 0;

          return Card(
            color: isCompleted ? green.withOpacity(0.3) : cardBg,
            margin: const EdgeInsets.symmetric(vertical: 8),
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
              side: BorderSide(
                color: isCompleted ? gold : gold.withOpacity(0.2),
                width: 1,
              ),
            ),
            child: Padding(
              padding: const EdgeInsets.all(16.0),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  Text(
                    item.text,
                    textDirection: TextDirection.rtl,
                    style: TextStyle(
                      color: isCompleted ? Colors.white70 : Colors.white,
                      fontSize: 15,
                      height: 1.6,
                    ),
                  ),
                  if (item.note != null && item.note!.isNotEmpty) ...[
                    const SizedBox(height: 8),
                    Text(
                      item.note!,
                      style: const TextStyle(color: gold, fontSize: 13, fontStyle: FontStyle.italic),
                    ),
                  ],
                  if (item.count != null) ...[
                    const SizedBox(height: 12),
                    Align(
                      alignment: Alignment.centerLeft,
                      child: ElevatedButton.styleFrom(
                        backgroundColor: isCompleted ? gold : green,
                      ).runtimeType == ElevatedButton ? ElevatedButton(
                        style: ElevatedButton.styleFrom(
                          backgroundColor: isCompleted ? gold.withOpacity(0.5) : green,
                          foregroundColor: Colors.white,
                          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
                        ),
                        onPressed: () {
                          setState(() {
                            if (remainingCounts[index]! > 0) {
                              remainingCounts[index] = remainingCounts[index]! - 1;
                            }
                          });
                        },
                        child: Text(
                          isCompleted ? 'تم الانتهاء ✓' : 'المتبقي: ${remainingCounts[index]}',
                          style: const TextStyle(fontWeight: FontWeight.bold),
                        ),
                      ) : Container(),
                    ),
                  ],
                ],
              ),
            ),
          );
        },
      ),
    );
  }
}
